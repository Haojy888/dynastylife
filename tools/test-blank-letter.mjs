import assert from 'node:assert/strict';
import { createStaticServer } from './serve.mjs';
import { launchBrowser } from './browser.mjs';
const server = createStaticServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await launchBrowser();
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`, { waitUntil: 'domcontentloaded' });
  const result = await page.evaluate(() => {
    startLife();
    const baseline = JSON.stringify(state);
    const pack = CAREER_STORY_PACKS['blank-letter'];
    let checks = 0;
    const check = (condition, message) => { checks += 1; if (!condition) throw new Error(message); };
    const reset = () => {
      state = normalizeState(JSON.parse(baseline));
      Object.assign(state, { gender: 'male', age: 30, year: 30, lastSettledYear: 30, currentEvent: null, eventResult: null, pendingAnnualEvent: null, pendingSurprise: null, pendingAchievement: null });
      Object.assign(state.stats, { money: 5000, physique: 95, knowledge: 70 });
      state.onboarding.seen = true;
      state.career = allCareers().find(career => careerKind(career) === 'caravan');
      Object.assign(view, { screen: 'game', page: 'main', tab: 'career', overlay: '' });
      startOrResumeCareerChapter('blank-letter');
    };
    const next = () => {
      state.eventResult = null;
      state.age = state.year = state.careerChapters.active.dueYear;
      state.currentEvent = annualCareerChapterEvent();
    };
    check(validateStoryContent().length === 0, '内容合同通过');
    const outcomes = new Set();
    let playablePaths = 0;
    for (let combination = 0; combination < 320; combination += 1) {
      reset();
      const path = [combination % 4, Math.floor(combination / 4) % 4, Math.floor(combination / 16) % 4, Math.floor(combination / 64)];
      let complete = true;
      for (let stage = 0; stage < 4; stage += 1) {
        const event = state.currentEvent;
        const choice = event.children[path[stage]];
        if (choice.disabled) { complete = false; break; }
        const money = state.stats.money;
        chooseOption(path[stage]);
        const record = state.careerChapters.completed[0];
        const ending = record && pack.endings.find(item => item.title === record.outcome);
        check(state.stats.money === money - (choice.cost || 0) + (choice.gain || 0) + (ending?.money || 0), '按真实选择与结局结钱，不虚发镖银');
        const settled = JSON.stringify(state);
        resolveCareerChapter(event, choice);
        check(JSON.stringify(state) === settled, '旧选项不得重放');
        if (stage < 3) next();
      }
      if (!complete) continue;
      playablePaths += 1;
      const record = state.careerChapters.completed[0];
      const good = ['白纸照夜', '无名渡口'].includes(record.outcome);
      outcomes.add(record.outcome);
      check(record.history.length === 4 && record.history.every((entry, index) => entry.year === 30 + index), '四幕年份与真实选择入册');
      check(state.heirlooms.items.length === (good ? 1 : 0), '仅两条对应结局留下行镖录');
      check(state.life.goals.includes('night-passage') === good, '成就与实际结局一致');
      check(careerProgressFor().records.successes === (good ? 1 : 0), '成功履历不将失信或守约冒称破案');
      const notebook = careerClueNotebook(record);
      const foundPaper = record.history.some(entry => entry.choiceId === 'trace-paper');
      check(notebook.includes('纸背的针孔') === foundPaper, '已完成的线索簿仅列真正取得的线索');
      const endingCash = state.stats.money;
      state.eventResult = null;
      startOrResumeCareerChapter('blank-letter');
      check(!state.careerChapters.active && state.stats.money === endingCash, '完结不可再次领镖银');
    }
    check(pack.endings.every(ending => outcomes.has(ending.title)), '六种结局全部真实可达');
    reset();
    chooseOption(3); next(); chooseOption(3); next();
    const locked = state.currentEvent.children[0];
    check(locked.disabled && locked.note.includes('针孔') && locked.note.includes('暂不可选'), '缺线索时仍说明本项内容与禁用原因');
    const missingBoth = careerChapterChoiceLockReason(state.careerChapters.active, locked);
    check(missingBoth.includes('纸背的针孔') && missingBoth.includes('早了一年的关牒') && !missingBoth.includes('paper-trace'), '缺少的线索用玩家可读的名字逐项说明');
    const beforeMissing = JSON.stringify(state);
    resolveCareerChapter(state.currentEvent, { id: locked.id, disabled: false });
    check(JSON.stringify(state) === beforeMissing, '伪造未禁用按钮不能绕过 requiresAll');
    state.stats.money = 0;
    state.currentEvent = buildCareerChapterEvent();
    check(state.currentEvent.children.some(choice => !choice.disabled), '零钱状态仍能继续剧情');
    reset();
    const opened = state.currentEvent;
    state.stats.money = 34;
    chooseOption(0);
    check(state.currentEvent === opened && state.careerChapters.active.history.length === 0, '显示后资金变化不得透支');
    state.stats.money = 5000;
    chooseOption(0); finishEventResult();
    startOrResumeCareerChapter('blank-letter');
    check(state.eventResult.title.includes('来年待续'), '同年不能跳过等待');
    finishEventResult();
    state.pendingCaravan = { routeId: 'county' };
    const waiting = JSON.stringify(state.careerChapters);
    startOrResumeCareerChapter('blank-letter');
    check(JSON.stringify(state.careerChapters) === waiting, '押镖途中不启动第二套结算');
    state.pendingCaravan = null;
    performCareerAction('resign');
    check(!state.careerChapters.active && state.careerChapters.completed[0].outcome === '转业中断', '辞业中断不发奖励');
    reset();
    chooseOption(0); next(); chooseOption(0); next(); chooseOption(0); next();
    const actor = npcById(state.careerChapters.active.actorId, true);
    actor.alive = false; actor.physique = 0;
    state.currentEvent = buildCareerChapterEvent();
    check(state.currentEvent.content.includes('接手的同业'), '身故后有明确接手者');
    chooseOption(0);
    check(!state.eventResult.text.includes('{partner}') && !state.eventResult.text.includes('你与陆听舟'), '结局不复活身故同业或泄漏占位符');
    reset(); chooseOption(0); finishEventResult();
    const unfinished = familyLifeCard(currentLifeRecord(), true);
    check(unfinished.includes('纸背的针孔') && !unfinished.includes('两份能对照的证词'), '未竟之卷也只保留先人实际取得的线索');
    check(careerChapterChoiceLockReason(state.careerChapters.active, { requiresAll: ['paper-trace', 'false-warrant'] }) === '还缺线索：早了一年的关牒', '已经取得的线索不再列入缺项');
    state.eventResult = { title: '旧档中的普通结果', text: '这份结果没有记录所属故事。', deltas: [] };
    check(!eventResultView().includes('chapter-clues'), '旧结果没有章节标识时不借用旁边故事的线索');
    state.eventResult = null;
    save();
    return { checks, playablePaths, theoreticalPaths: 320, endings: [...outcomes], career: state.career.name, money: state.stats.money };
  });
  await page.reload({ waitUntil: 'domcontentloaded' });
  assert.equal(await page.evaluate(() => state.careerChapters.active.id), 'blank-letter');
  assert.equal(await page.evaluate(() => state.careerChapters.active.history.length), 1);
  assert.equal(await page.evaluate(() => state.stats.money), result.money);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ...result, reload: true, errors }));
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
